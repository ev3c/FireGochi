let lang = localStorage.getItem(KEY) === 'en' ? 'en' : 'es';
const listeners = new Set();

function fill(s, vars) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? `{${k}}` : String(vars[k])));
}

export function getLang() {
  return lang;
}

export function t(key, vars) {
  const s = STR[lang][key] ?? STR.es[key] ?? key;
  return fill(s, vars);
}

export function setLang(next) {
  if (next !== 'es' && next !== 'en') return;
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* privado */ }
  for (const fn of listeners) fn(lang);
}

export function onLang(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export const fuelName = (id) => t(`fuel.${id}.name`);
export const fuelShort = (id) => t(`fuel.${id}.short`);
export const fuelDesc = (id) => t(`fuel.${id}.desc`);
